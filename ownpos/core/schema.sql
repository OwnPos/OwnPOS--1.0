-- OwnPOS database (PostgreSQL 13+). Runs every time a station connects: everything is CREATE ... IF NOT EXISTS.
-- New columns for existing stores are added by the migrations in db.py.
-- Money columns are INTEGER cents. Quantities and costs are DOUBLE PRECISION (quantities rounded to 3 decimals).
-- Dates are text 'YYYY-MM-DD', times text 'YYYY-MM-DD HH:MM:SS', always in store time from the server clock.

CREATE TABLE IF NOT EXISTS meta (key TEXT PRIMARY KEY, value TEXT);
CREATE TABLE IF NOT EXISTS settings (key TEXT PRIMARY KEY, value TEXT);

CREATE TABLE IF NOT EXISTS roles (
    code TEXT PRIMARY KEY,
    name TEXT NOT NULL,
    permissions TEXT NOT NULL DEFAULT '',          -- permission codes separated by commas
    active INTEGER NOT NULL DEFAULT 1,
    sort INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username TEXT NOT NULL,
    full_name TEXT NOT NULL,
    title TEXT,                                     -- job title shown on screen, e.g. "Store manager"
    role TEXT NOT NULL DEFAULT 'cashier',
    phone TEXT,
    email TEXT,
    pin_hash TEXT,
    password_hash TEXT,
    pin_index TEXT,                                 -- HMAC of the PIN for quick lookup (see auth.py)
    pay_type TEXT NOT NULL DEFAULT 'hourly' CHECK (pay_type IN ('hourly','salary','none')),
    pay_rate INTEGER NOT NULL DEFAULT 0,            -- cents per hour (hourly) or per week (salary)
    overtime INTEGER NOT NULL DEFAULT 1,            -- 1 = hours over 40 in a week at 1.5x (hourly only)
    active INTEGER NOT NULL DEFAULT 1,
    notes TEXT,
    created_at TEXT NOT NULL DEFAULT to_char(localtimestamp, 'YYYY-MM-DD HH24:MI:SS')
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_users_username ON users (lower(username));
CREATE UNIQUE INDEX IF NOT EXISTS ux_users_pin ON users (pin_index) WHERE active = 1 AND pin_index IS NOT NULL;

CREATE TABLE IF NOT EXISTS accounts (
    code TEXT PRIMARY KEY,
    name TEXT NOT NULL,
    type TEXT NOT NULL CHECK (type IN ('asset','liability','equity','income','contra_income','cogs','expense')),
    subtype TEXT,                                   -- 'cash' or 'bank' for money accounts
    system INTEGER NOT NULL DEFAULT 0,
    active INTEGER NOT NULL DEFAULT 1
);

CREATE TABLE IF NOT EXISTS tax_codes (
    code TEXT PRIMARY KEY,
    name TEXT NOT NULL,
    rate DOUBLE PRECISION NOT NULL DEFAULT 0,       -- percent, e.g. 7.0
    active INTEGER NOT NULL DEFAULT 1
);

CREATE TABLE IF NOT EXISTS departments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    code TEXT,
    income_account TEXT NOT NULL DEFAULT '4000' REFERENCES accounts(code),
    default_tax_code TEXT REFERENCES tax_codes(code),
    margin_target DOUBLE PRECISION NOT NULL DEFAULT 0,   -- percent of price
    color TEXT,
    show_on_register INTEGER NOT NULL DEFAULT 1,
    sort INTEGER NOT NULL DEFAULT 0,
    active INTEGER NOT NULL DEFAULT 1
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_departments_name ON departments (lower(name));

CREATE TABLE IF NOT EXISTS lookups (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    list_name TEXT NOT NULL,
    code TEXT NOT NULL,
    name TEXT NOT NULL,
    value TEXT,
    sort INTEGER NOT NULL DEFAULT 0,
    active INTEGER NOT NULL DEFAULT 1,
    UNIQUE (list_name, code)
);

CREATE TABLE IF NOT EXISTS payment_methods (
    code TEXT PRIMARY KEY,
    name TEXT NOT NULL,
    account TEXT NOT NULL REFERENCES accounts(code),
    is_cash INTEGER NOT NULL DEFAULT 0,
    is_card INTEGER NOT NULL DEFAULT 0,
    requires_ref INTEGER NOT NULL DEFAULT 0,
    requires_customer INTEGER NOT NULL DEFAULT 0,
    opens_drawer INTEGER NOT NULL DEFAULT 0,
    on_register INTEGER NOT NULL DEFAULT 1,
    sort INTEGER NOT NULL DEFAULT 0,
    active INTEGER NOT NULL DEFAULT 1
);

CREATE TABLE IF NOT EXISTS vendors (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code TEXT,
    name TEXT NOT NULL,
    contact TEXT,
    phone TEXT,
    email TEXT,
    address TEXT,
    city TEXT,
    state TEXT,
    zip TEXT,
    account_no TEXT,                                -- the store's account number with this vendor
    terms_days INTEGER NOT NULL DEFAULT 0,
    active INTEGER NOT NULL DEFAULT 1,
    notes TEXT,
    created_at TEXT NOT NULL DEFAULT to_char(localtimestamp, 'YYYY-MM-DD HH24:MI:SS')
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_vendors_code ON vendors (lower(code)) WHERE code IS NOT NULL AND code <> '';

CREATE TABLE IF NOT EXISTS items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_no TEXT NOT NULL,                          -- store's item number (QuickBooks "Item #")
    upc TEXT,
    upc_key TEXT GENERATED ALWAYS AS (NULLIF(ltrim(upc, '0'), '')) STORED,
    alt_lookup TEXT,                                -- second code (QuickBooks "ALU")
    name TEXT NOT NULL,                             -- description shown on the receipt
    department_id BIGINT REFERENCES departments(id),
    kind TEXT NOT NULL DEFAULT 'inventory' CHECK (kind IN ('inventory','non_inventory','service')),
    size TEXT,                                      -- e.g. 750ML, 12OZ
    attribute TEXT,                                 -- e.g. flavour, vintage
    unit TEXT NOT NULL DEFAULT 'ea',                -- the unit stock is counted in (bottle / can / each)
    price1 INTEGER NOT NULL DEFAULT 0,              -- Regular price (cents, before tax)
    price2 INTEGER NOT NULL DEFAULT 0,              -- price levels 2-5 (0 = use regular price)
    price3 INTEGER NOT NULL DEFAULT 0,
    price4 INTEGER NOT NULL DEFAULT 0,
    price5 INTEGER NOT NULL DEFAULT 0,
    msrp INTEGER NOT NULL DEFAULT 0,
    tax_code TEXT NOT NULL DEFAULT 'IN7' REFERENCES tax_codes(code),
    cost_avg DOUBLE PRECISION NOT NULL DEFAULT 0,   -- cents per unit (moving average)
    last_cost DOUBLE PRECISION NOT NULL DEFAULT 0,
    on_hand DOUBLE PRECISION NOT NULL DEFAULT 0,
    reorder_point DOUBLE PRECISION NOT NULL DEFAULT 0,
    reorder_qty DOUBLE PRECISION NOT NULL DEFAULT 0,
    vendor_id BIGINT REFERENCES vendors(id),
    vendor_item_no TEXT,
    purchase_unit TEXT,                             -- unit Receiving starts in (e.g. CASE); empty = own unit
    purchase_factor DOUBLE PRECISION NOT NULL DEFAULT 1,
    on_register INTEGER NOT NULL DEFAULT 0,         -- quick button on the sale screen
    tile_color TEXT,
    sort INTEGER NOT NULL DEFAULT 0,
    active INTEGER NOT NULL DEFAULT 1,
    notes TEXT,
    created_at TEXT NOT NULL DEFAULT to_char(localtimestamp, 'YYYY-MM-DD HH24:MI:SS'),
    updated_at TEXT
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_items_item_no ON items (lower(item_no));
CREATE INDEX IF NOT EXISTS ix_items_upc ON items (upc);
CREATE INDEX IF NOT EXISTS ix_items_upc_key ON items (upc_key);
CREATE INDEX IF NOT EXISTS ix_items_alt ON items (lower(alt_lookup));
CREATE INDEX IF NOT EXISTS ix_items_name ON items (lower(name));
CREATE INDEX IF NOT EXISTS ix_items_department ON items (department_id);
CREATE INDEX IF NOT EXISTS ix_items_vendor ON items (vendor_id);

-- other units of one item (6PK = 6, CASE = 24). Stock stays in items.unit; factor = item units in one of this unit.
CREATE TABLE IF NOT EXISTS item_units (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id BIGINT NOT NULL REFERENCES items(id),
    unit TEXT NOT NULL,
    factor DOUBLE PRECISION NOT NULL CHECK (factor > 0),
    price INTEGER NOT NULL DEFAULT 0,               -- own Regular price of one of this unit (0 = factor x item price)
    barcode TEXT,
    barcode_key TEXT GENERATED ALWAYS AS (NULLIF(ltrim(barcode, '0'), '')) STORED,
    sort INTEGER NOT NULL DEFAULT 0,
    UNIQUE (item_id, unit)
);
CREATE INDEX IF NOT EXISTS ix_item_units_barcode ON item_units (barcode);
CREATE INDEX IF NOT EXISTS ix_item_units_barcode_key ON item_units (barcode_key);

