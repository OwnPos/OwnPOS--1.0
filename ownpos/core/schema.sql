-- ---------------------------------------------------------------------------------------------
-- Locked records. Issued receipts, their lines and payments, journal entries, stock movements and the
-- audit log can never be changed or deleted. Corrections are new documents (returns, reversing
-- entries, adjustments), so the history always adds up and every change is visible.
-- ---------------------------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION ownpos_refuse() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION '%', TG_ARGV[0];
END $$;

CREATE OR REPLACE FUNCTION ownpos_sales_guard() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.receipt_no IS DISTINCT FROM OLD.receipt_no OR NEW.total IS DISTINCT FROM OLD.total
       OR NEW.tax IS DISTINCT FROM OLD.tax OR NEW.taxable IS DISTINCT FROM OLD.taxable
       OR NEW.nontaxable IS DISTINCT FROM OLD.nontaxable OR NEW.discount IS DISTINCT FROM OLD.discount
       OR NEW.subtotal IS DISTINCT FROM OLD.subtotal OR NEW.sale_date IS DISTINCT FROM OLD.sale_date
       OR NEW.created_at IS DISTINCT FROM OLD.created_at OR NEW.customer_id IS DISTINCT FROM OLD.customer_id
       OR NEW.user_id IS DISTINCT FROM OLD.user_id OR NEW.doc_type IS DISTINCT FROM OLD.doc_type
       OR NEW.seq IS DISTINCT FROM OLD.seq OR NEW.sale_key IS DISTINCT FROM OLD.sale_key
       OR NEW.cost_total IS DISTINCT FROM OLD.cost_total OR NEW.ref_sale_id IS DISTINCT FROM OLD.ref_sale_id
       OR NEW.station_id IS DISTINCT FROM OLD.station_id OR NEW.shift_id IS DISTINCT FROM OLD.shift_id
       OR NEW.print_count < OLD.print_count OR (OLD.is_active = 0 AND NEW.is_active = 1) THEN
        RAISE EXCEPTION 'Issued receipts are locked and cannot be changed';
    END IF;
    RETURN NEW;
END $$;

DO $$
DECLARE
    t RECORD;
BEGIN
    FOR t IN SELECT * FROM (VALUES
        ('trg_sales_no_delete', 'sales', 'DELETE', 'Issued receipts cannot be deleted; make a return instead'),
        ('trg_sale_lines_locked', 'sale_lines', 'UPDATE', 'Receipt lines are locked'),
        ('trg_sale_lines_no_delete', 'sale_lines', 'DELETE', 'Receipt lines cannot be deleted'),
        ('trg_tenders_locked', 'sale_tenders', 'UPDATE', 'Payments on a receipt are locked'),
        ('trg_tenders_no_delete', 'sale_tenders', 'DELETE', 'Payments on a receipt cannot be deleted'),
        ('trg_journal_locked', 'journal', 'UPDATE', 'Posted journal entries are locked; post a reversing entry'),
        ('trg_journal_no_delete', 'journal', 'DELETE', 'Posted journal entries cannot be deleted'),
        ('trg_jl_locked', 'journal_lines', 'UPDATE', 'Posted journal lines are locked'),
        ('trg_jl_no_delete', 'journal_lines', 'DELETE', 'Posted journal lines cannot be deleted'),
        ('trg_moves_locked', 'stock_moves', 'UPDATE', 'Stock movements are locked'),
        ('trg_moves_no_delete', 'stock_moves', 'DELETE', 'Stock movements cannot be deleted'),
        ('trg_audit_locked', 'audit_log', 'UPDATE', 'The audit log cannot be changed'),
        ('trg_audit_no_delete', 'audit_log', 'DELETE', 'The audit log cannot be deleted')
    ) AS v(name, tbl, ev, msg) LOOP
        IF NOT EXISTS (SELECT 1 FROM pg_trigger WHERE tgname = t.name) THEN
            EXECUTE format('CREATE TRIGGER %I BEFORE %s ON %I FOR EACH ROW EXECUTE FUNCTION ownpos_refuse(%L)',
                           t.name, t.ev, t.tbl, t.msg);
        END IF;
    END LOOP;
    IF NOT EXISTS (SELECT 1 FROM pg_trigger WHERE tgname = 'trg_sales_locked') THEN
        CREATE TRIGGER trg_sales_locked BEFORE UPDATE ON sales FOR EACH ROW EXECUTE FUNCTION ownpos_sales_guard();
    END IF;
END $$;
